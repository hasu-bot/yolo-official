// Install Playwright locally or provide PLAYWRIGHT_MODULE=/absolute/path/to/playwright.
import { createRequire } from 'node:module';
import { mkdir, writeFile, rm } from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { startPreview } from '../scripts/preview.mjs';
import { createDemo } from '../scripts/demo.mjs';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const output = path.resolve(process.env.EVIDENCE_DIR || '../evidence');
await mkdir(output, { recursive: true });
const root = await createDemo();
const demo = await startPreview({ root, port: 0 });
const production = await startPreview({ port: 0 });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const findings = [];
const pass = text => { findings.push(text); console.log(`PASS ${text}`); };
async function capture(page, name) {
  await page.evaluate(async () => {
    await document.fonts.ready;
    await Promise.all([...document.images].map(img => img.decode().catch(() => {})));
  });
  // Paint clipped image regions before a full-page capture, including offscreen cards.
  for (const frame of await page.locator('.talent-card-photo, .profile-portrait, .profile-gallery figure').all()) {
    await frame.scrollIntoViewIfNeeded();
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  }
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await page.screenshot({ path: path.join(output, name), fullPage: true });
}
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, permissions: ['clipboard-read', 'clipboard-write'] });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const failedLocalRequests = [];
  page.on('response', response => { if (response.url().startsWith(demo.url) && response.status() >= 400) failedLocalRequests.push(`${response.status()} ${response.url()}`); });
  await page.goto(demo.url + '/talents/');
  await page.locator('.talent-card').first().waitFor();
  await page.evaluate(() => document.fonts.ready);
  assert.equal(await page.locator('.talent-card:visible').count(), 4);
  await capture(page, 'models-demo-desktop.png');
  pass('demo is visibly labelled, noindexed and contains 4 fictional profiles');
  assert.match(await page.locator('.demo-notice').innerText(), /架空/);
  assert.equal(await page.locator('meta[name=robots]').getAttribute('content'), 'noindex, nofollow');
  const cardTop = await page.locator('.talent-card-photo').first().evaluate(element => element.getBoundingClientRect().top);
  assert.ok(cardTop < 650, `portrait grid is too far below the fold: ${cardTop}`);
  assert.equal(await page.locator('.talents-grid').evaluate(element => getComputedStyle(element).gridTemplateColumns.split(' ').length), 4);
  const sectionOrder = await page.locator('main > section').evaluateAll(elements => elements.map(element => element.id || element.className));
  assert.deepEqual(sectionOrder.slice(1), ['models', 'growth', 'casting']);
  assert.match(await page.locator('.growth-content article').first().innerText(), /これまでの活動/);
  assert.match(await page.locator('.growth-content article').last().innerText(), /これから目指すこと/);
  assert.equal(await page.locator('.growth-links a[href="/history/"]').count(), 1);
  await page.getByRole('button', { name: 'ファッション', exact: true }).click();
  assert.equal(await page.locator('.talent-card:visible').count(), 2);
  assert.match(page.url(), /category=fashion/);
  await page.getByRole('button', { name: 'ビューティー', exact: true }).click();
  assert.equal(await page.locator('.talent-card:visible').count(), 1);
  await page.getByRole('button', { name: 'ライフスタイル', exact: true }).click();
  assert.equal(await page.locator('.talent-card:visible').count(), 2);
  await page.getByRole('button', { name: 'すべて', exact: true }).click();
  pass('reference layout: compact intro, four portraits, genre filters, then existing activity records, future support direction and casting guide');
  await page.locator('.talents-extra-filters summary').click();
  await page.getByRole('button', { name: '映像・MV', exact: true }).click();
  assert.match(page.url(), /work=film/);
  assert.equal(await page.locator('.talent-card:visible').count(), 1);
  await page.locator('.talent-card:visible a').click();
  await page.waitForURL('**/talents/sample-b/');
  assert.match(await page.locator('h1').innerText(), /サンプル B/);
  await page.goBack();
  assert.equal(await page.locator('.talent-card:visible').count(), 1);
  await page.goForward();
  await page.waitForURL('**/talents/sample-b/');
  await page.goto(demo.url + '/talents/sample-b/');
  assert.match(await page.locator('h1').innerText(), /サンプル B/);
  pass('list → detail → Back/Forward and direct detail reload preserve route and filter');
  await page.getByRole('link', { name: /サンプル B.*出演を相談する/ }).click();
  await page.waitForURL('**/#casting');
  assert.match(await page.locator('.casting-selection').innerText(), /サンプル B/);
  assert.deepEqual(await page.locator('.booking-steps h3').allTextContents(), ['企画内容を相談', '本人の希望・日程を確認', '見積もり・契約相手を確認', '合意後に出演確定']);
  assert.deepEqual(await page.locator('.booking-checklist dt').allTextContents(), ['撮影の目的・内容', '希望日時', '撮影・出演場所', '使用媒体', '掲載・使用期間', 'ご予算']);
  assert.equal(await page.locator('body').evaluate(element => getComputedStyle(element).backgroundColor), 'rgb(255, 255, 255)');
  assert.equal(await page.locator('.talents-casting').evaluate(element => getComputedStyle(element).backgroundColor), 'rgb(255, 255, 255)');
  assert.match(await page.locator('.booking-status-note').innerText(), /出演は確定しません/);
  const conditions = await page.locator('.booking-conditions').innerText();
  for (const term of ['契約する相手', '出演料', '調整料', '交通費', '支払条件', '使用媒体', '使用期間', '地域', '二次利用', '競合', '変更', '延期', '中止']) assert.ok(conditions.includes(term), term);
  assert.match(await page.locator('.booking-consent-note').innerText(), /承諾を意味しません/);
  pass('white backgrounds and casting guide explain request → availability → estimate → agreement, with all six brief fields');
  await page.getByRole('button', { name: /相談メモをコピー/ }).click();
  await page.waitForFunction(() => document.querySelector('.copy-status').textContent.includes('コピーしました'));
  const copied = await page.evaluate(() => navigator.clipboard.readText());
  assert.match(copied, /サンプル B/);
  for (const term of ['撮影目的', '希望日時', '場所', 'ご予算', '使用媒体', '掲載・使用期間']) assert.ok(copied.includes(term));
  const castingLink = page.getByRole('link', { name: /制作・出演について相談する/ });
  assert.equal(await castingLink.getAttribute('href'), '/casting/?model=sample-b');
  assert.equal(await castingLink.getAttribute('target'), null);
  pass('profile consultation retains model name; clipboard memo includes budget/media/period and central casting form link');
  await capture(page, 'profile-demo-desktop.png');
  await page.goto(demo.url + '/talents/?work=event');
  assert.equal(await page.locator('.talent-card:visible').count(), 0);
  assert.equal(await page.locator('[data-filter-empty]:visible').count(), 1);
  await page.getByRole('button', { name: /すべてのモデルを見る/ }).click();
  await page.locator('.talents-extra-filters summary').click();
  assert.equal(await page.locator('.talent-card:visible').count(), 4);
  await page.getByRole('button', { name: '写真・ポートレート', exact: true }).focus();
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('.talent-card:visible').count(), 2);
  await page.keyboard.press('Tab');
  await page.keyboard.press('Space');
  assert.equal(await page.locator('.talent-card:visible').count(), 1);
  pass('empty filter, reset, Enter/Space and native focus navigation work');
  await page.goto(demo.url + '/talents/?work=unknown');
  assert.equal(await page.locator('.talent-card:visible').count(), 4);
  pass('unknown filter safely falls back to all profiles');
  for (const width of [320, 375, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    for (const route of ['/talents/', '/talents/sample-a/']) {
      await page.goto(demo.url + route);
      const dimensions = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, viewport: innerWidth, unloaded: [...document.images].filter(img => !img.complete || !img.naturalWidth).length }));
      assert.ok(dimensions.scroll <= dimensions.viewport, `overflow at ${width} ${route}: ${JSON.stringify(dimensions)}`);
      // Force lazy images into view before checking them.
      for (const image of await page.locator('img').all()) await image.scrollIntoViewIfNeeded();
      await page.waitForFunction(() => [...document.images].every(img => img.complete && img.naturalWidth));
    }
  }
  pass('320/375/768/1024/1440px: list and profile have no horizontal overflow and all images load');
  await page.setViewportSize({ width: 375, height: 812 });
  await page.goto(demo.url + '/talents/');
  await capture(page, 'models-demo-mobile.png');
  await page.goto(demo.url + '/talents/sample-a/');
  await capture(page, 'profile-demo-mobile.png');
  const fallbackPage = await context.newPage();
  await fallbackPage.addInitScript(() => Object.defineProperty(navigator, 'clipboard', { value: { writeText: () => Promise.reject(new Error('clipboard denied')) } }));
  await fallbackPage.goto(demo.url + '/talents/sample-a/');
  await fallbackPage.getByRole('button', { name: /相談メモをコピー/ }).click();
  await fallbackPage.locator('.copy-fallback:visible').waitFor();
  assert.match(await fallbackPage.locator('.copy-fallback').inputValue(), /サンプル A/);
  pass('denied clipboard exposes selectable consultation memo');
  await fallbackPage.close();
  assert.deepEqual(errors, []);
  assert.deepEqual(failedLocalRequests, []);
  pass('no JavaScript errors or missing local demo assets');
  await page.goto(production.url + '/talents/');
  assert.match(await page.locator('.talents-empty').innerText(), /公開中のプロフィールはありません/);
  assert.equal(await page.locator('.talent-card').count(), 0);
  assert.equal(await page.locator('.demo-notice').count(), 0);
  const response = await page.goto(production.url + '/talents/sample-a/');
  assert.equal(response.status(), 404);
  assert.ok(!(await page.content()).includes('サンプル A'));
  pass('production default has no profiles or fictional samples; unpublished direct URL returns 404');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(production.url + '/talents/');
  await capture(page, 'models-empty-desktop.png');
  await page.setViewportSize({ width: 375, height: 812 });
  await page.reload();
  await capture(page, 'models-empty-mobile.png');
  await page.goto(production.url + '/');
  assert.equal(await page.locator('header a[href="/talents/"]').count(), 1);
  await page.locator('[data-menu-button]').click();
  await page.locator('[data-mobile-nav] a[href="/talents/"]').click();
  await page.waitForURL('**/talents/');
  await page.goto(production.url + '/model/');
  await page.locator('#entry').waitFor();
  await page.waitForFunction(() => !!document.querySelector('#model-application-form'), { timeout: 15000 });
  assert.ok(await page.locator('input, select, textarea').count() > 0);
  pass('homepage enters model listing; existing application form loads without submission');
  const nojs = await browser.newContext({ javaScriptEnabled: false, viewport: { width: 375, height: 812 } });
  const simple = await nojs.newPage();
  await simple.goto(demo.url + '/talents/');
  assert.equal(await simple.locator('.talent-card').count(), 4);
  await simple.locator('.talent-card a').first().click();
  assert.match(simple.url(), /sample-a/);
  assert.equal(await simple.getByRole('link', { name: /制作・出演について相談する/ }).count(), 1);
  pass('without JavaScript, listing, profile and casting and application links remain available');
  await nojs.close();
  await context.close();
} finally {
  await writeFile(path.join(output, 'browser-results.json'), JSON.stringify({ passed: findings, screenshots: ['models-empty-desktop.png', 'models-empty-mobile.png', 'models-demo-desktop.png', 'models-demo-mobile.png', 'profile-demo-desktop.png', 'profile-demo-mobile.png'] }, null, 2));
  await browser.close();
  await Promise.all([demo, production].map(({ server }) => new Promise(resolve => server.close(resolve))));
  await rm(root, { recursive: true, force: true });
}
